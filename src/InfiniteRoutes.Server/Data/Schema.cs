using Microsoft.EntityFrameworkCore;

namespace InfiniteRoutes.Server.Data;

/// <summary>
/// Keeps the database's tables up to date. A new database is created whole at <see cref="Current"/>; an older one is
/// upgraded step by step with the statements below (each written for SQLite and for PostgreSQL), and the version kept
/// in a one-row table <c>SchemaInfo</c>. Add a step whenever the model in <see cref="IrDb"/> changes.
/// </summary>
public static class Schema
{
    public const int Current = 3;

    /// <summary>Statements taking the schema from version n to n + 1, for SQLite and for PostgreSQL.</summary>
    static readonly (string[] Sqlite, string[] Postgres)[] Steps =
    [
        // 1 → 2: staff roles, two-factor codes, the game state on characters, the audit log.
        (
            [
                """ALTER TABLE "Accounts" ADD COLUMN "Role" TEXT NOT NULL DEFAULT 'Player'""",
                """ALTER TABLE "Accounts" ADD COLUMN "TotpSecret" BLOB NULL""",
                """ALTER TABLE "Accounts" ADD COLUMN "TotpEnabled" INTEGER NOT NULL DEFAULT 0""",
                """ALTER TABLE "Accounts" ADD COLUMN "TotpLastStep" INTEGER NOT NULL DEFAULT 0""",
                """ALTER TABLE "Characters" ADD COLUMN "StateJson" TEXT NULL""",
                """CREATE TABLE "AuditEntries" ("Id" INTEGER NOT NULL CONSTRAINT "PK_AuditEntries" PRIMARY KEY AUTOINCREMENT, "Time" TEXT NOT NULL, "AccountId" INTEGER NOT NULL, "Actor" TEXT NOT NULL, "Role" TEXT NOT NULL, "Action" TEXT NOT NULL, "Target" TEXT NOT NULL, "Details" TEXT NOT NULL)""",
            ],
            [
                """ALTER TABLE "Accounts" ADD COLUMN "Role" text NOT NULL DEFAULT 'Player'""",
                """ALTER TABLE "Accounts" ADD COLUMN "TotpSecret" bytea NULL""",
                """ALTER TABLE "Accounts" ADD COLUMN "TotpEnabled" boolean NOT NULL DEFAULT FALSE""",
                """ALTER TABLE "Accounts" ADD COLUMN "TotpLastStep" bigint NOT NULL DEFAULT 0""",
                """ALTER TABLE "Characters" ADD COLUMN "StateJson" text NULL""",
                """CREATE TABLE "AuditEntries" ("Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "Time" timestamp with time zone NOT NULL, "AccountId" bigint NOT NULL, "Actor" text NOT NULL, "Role" text NOT NULL, "Action" text NOT NULL, "Target" text NOT NULL, "Details" text NOT NULL)""",
            ]
        ),
        // 2 → 3: chat mutes on accounts.
        (
            [
                """ALTER TABLE "Accounts" ADD COLUMN "MutedUntil" TEXT NULL""",
                """ALTER TABLE "Accounts" ADD COLUMN "MuteReason" TEXT NULL""",
            ],
            [
                """ALTER TABLE "Accounts" ADD COLUMN "MutedUntil" timestamp with time zone NULL""",
                """ALTER TABLE "Accounts" ADD COLUMN "MuteReason" text NULL""",
            ]
        ),
    ];

    /// <summary>Creates or upgrades the database; returns the version it was at (0 for a new one).</summary>
    public static int Ensure(IrDb db)
    {
        var created = db.Database.EnsureCreated();
        db.Database.ExecuteSqlRaw("""CREATE TABLE IF NOT EXISTS "SchemaInfo" ("Version" INTEGER NOT NULL)""");
        var version = created ? Current : Read(db) ?? 1;   // a database from before SchemaInfo is version 1
        var was = created ? 0 : version;
        var postgres = db.Database.ProviderName?.Contains("Npgsql", StringComparison.Ordinal) == true;
        while (version < Current)
        {
            using var tx = db.Database.BeginTransaction();
            foreach (var sql in postgres ? Steps[version - 1].Postgres : Steps[version - 1].Sqlite)
                db.Database.ExecuteSqlRaw(sql);
            version++;
            Write(db, version);
            tx.Commit();
        }
        Write(db, version);
        return was;
    }

    static int? Read(IrDb db) =>
        db.Database.SqlQueryRaw<int>("""SELECT "Version" AS "Value" FROM "SchemaInfo" """).AsEnumerable().Cast<int?>().FirstOrDefault();

    static void Write(IrDb db, int version)
    {
        db.Database.ExecuteSqlRaw("""DELETE FROM "SchemaInfo" """);
        db.Database.ExecuteSql($"""INSERT INTO "SchemaInfo" ("Version") VALUES ({version})""");
    }
}
