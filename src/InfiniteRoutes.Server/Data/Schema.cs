    /// <summary>Creates or upgrades the database; returns the version it was at (0 for a new one).</summary>
    public static int Ensure(IrDb db)
    {
        var created = db.Database.EnsureCreated();
        db.Database.ExecuteSqlRaw("""CREATE TABLE IF NOT EXISTS "SchemaInfo" ("Version" INTEGER NOT NULL)""");
        var version = created ? Current : Read(db) ?? 1;   // a database from before SchemaInfo is version 1
        var was = created ? 0 : version;
        var postgres = db.Database.ProviderName?.Contains("Npgsql", StringComparison.Ordinal) == true;
        while (version < Current)
        {
            using var tx = db.Database.BeginTransaction();
            foreach (var sql in postgres ? Steps[version - 1].Postgres : Steps[version - 1].Sqlite)
                db.Database.ExecuteSqlRaw(sql);
            version++;
            Write(db, version);
            tx.Commit();
        }
        Write(db, version);
        return was;
    }

    static int? Read(IrDb db) =>
        db.Database.SqlQueryRaw<int>("""SELECT "Version" AS "Value" FROM "SchemaInfo" """).AsEnumerable().Cast<int?>().FirstOrDefault();

    static void Write(IrDb db, int version)
    {
        db.Database.ExecuteSqlRaw("""DELETE FROM "SchemaInfo" """);
        db.Database.ExecuteSql($"""INSERT INTO "SchemaInfo" ("Version") VALUES ({version})""");
    }
